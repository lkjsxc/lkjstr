export async function authorizationCases({c, fixture, fake, origin, check}) {
  const account=fixture.first.pubkey, relay=origin.replace('http:','ws:');
  await c.send(0,{t:'relays',relays:[{url:relay,read:true,write:true,search:true}]});
  const add={a:'account.add',how:'key',key:'bunker://'+account+'?relay='+encodeURIComponent(relay+'/bunker')};
  const count=async client=>(await c.all(client)).filter(m=>m.t==='signer.auth').length;
  const held=()=>fixture.pending().at(-1);
  const clear=async(id,client=0)=>c.until(ms=>ms.some(m=>m.t==='signer.auth.clear'&&m.id===id),client);
  const noOther=async n=>(await c.all(n)).every(m=>m.t!=='signer.auth');
  fixture.configure(origin,['connect','get_public_key']);
  const req=await c.begin(add), connect=await c.challenge();
  check('connect challenge identifies verified peer and exact action before account discovery',
    connect.peer===account&&connect.method==='connect'&&connect.account===undefined&&connect.actionReq===req);
  check('another live client receives no connect authorization URL',await noOther(1));
  check('intermediate auth URL does not settle account discovery',!(await c.all(0)).some(m=>m.t==='result'&&m.req===req));
  const firstHeld=held(), firstExpiry=connect.expiresAt;
  await fixture.challenge(firstHeld,connect.url);await c.page.waitForTimeout(80);
  check('identical challenge is deduplicated without extending its deadline',await count(0)===1);
  await fixture.challenge(firstHeld,origin+'/authorize?fixture=changed');
  const changed=await c.challenge(1);
  check('changed URL retains its opaque handle and original deadline',changed.id===connect.id&&changed.expiresAt===firstExpiry);
  fixture.release(firstHeld);await clear(connect.id);
  const pubkey=await c.challenge(2);
  check('get_public_key remains independently owned during discovery',pubkey.method==='get_public_key'&&pubkey.actionReq===req&&pubkey.id!==connect.id);
  fixture.release(held());check('later same-id RPC response completes bunker discovery',(await c.result(req)).ok);
  const state=await c.all(0);
  check('terminal discovery result follows the final authorization clear',state.findIndex(m=>m.t==='signer.auth.clear'&&m.id===pubkey.id)<state.findIndex(m=>m.t==='result'&&m.req===req));
  fixture.configure(origin,['sign_event']);
  const before=await count(0), post=await c.begin({a:'publish',as:account,what:{k:'note',draft:{text:'owned auth fixture publication'}}});
  const sign=await c.challenge(before);
  check('public signing challenge carries its existing action and account ownership',sign.method==='sign_event'&&sign.actionReq===post&&sign.account===account);
  await c.send(1,{t:'signer.auth.cancel',id:sign.id});await c.page.waitForTimeout(80);
  check('wrong client cannot cancel or clear another port authorization',fixture.open(held())&&!(await c.all(0)).some(m=>m.t==='signer.auth.clear'&&m.id===sign.id));
  fixture.release(held());check('authorized ordinary signing publishes only the intended loopback event',(await c.result(post)).ok);
  const beforeInbox=await count(0), inbox=await c.begin({a:'dm.relays.save',as:account,relays:[relay]});
  const privateSign=await c.challenge(beforeInbox);
  check('private inbox signing has exact initiating client and account',privateSign.account===account&&await noOther(1));
  fixture.release(held());check('private signing resumes after authorization',(await c.result(inbox)).ok);
  fixture.configure(origin,['nip44_encrypt']);
  const beforeArchive=await count(0), archive=await c.begin({a:'dm.draft.load',as:account,tab:'auth-fixture'});
  const encrypt=await c.challenge(beforeArchive);
  check('private encryption challenge retains its bounded original RPC deadline',encrypt.method==='nip44_encrypt'&&encrypt.account===account&&encrypt.expiresAt-Date.now()<=60_000);
  fixture.release(held());check('private archive initialization resumes under its original owner',(await c.result(archive)).ok);
  fixture.configure(origin,['nip44_decrypt']);
  let beforeList=await count(0);
  await c.send(0,{t:'open',sub:'private-auth',query:{source:'mutes',account,privateLists:true},visible:true});
  await c.send(0,{t:'hint',hint:{visibleSubs:['private-auth'],pageHidden:false,idle:false,saveData:false}});
  const decrypt=await c.challenge(beforeList), pending=held();
  check('private list decryption exposes an account-owned NIP44 challenge',decrypt.method==='nip44_decrypt'&&decrypt.account===account);
  await c.send(0,{t:'close',sub:'private-auth'});await clear(decrypt.id);
  await c.until(()=>!fixture.open(pending));
  check('closing the owning private view aborts authorization and its RPC socket',!fixture.open(pending));
  check('late authorized reply cannot resume a closed private read',fixture.release(pending)===false);
  beforeList=await count(0);
  await c.send(0,{t:'open',sub:'private-reopened',query:{source:'mutes',account,privateLists:true},visible:true});
  await c.send(0,{t:'hint',hint:{visibleSubs:['private-reopened'],pageHidden:false,idle:false,saveData:false}});
  const reopened=await c.challenge(beforeList);
  check('reopened private view receives a fresh authorization handle',reopened.id!==decrypt.id);
  fixture.release(held());
  await c.until(ms=>ms.some(m=>m.t==='state'&&m.sub==='private-reopened'&&m.state.privateLists?.phase==='ready'));
  fixture.configure(origin,['nip04_decrypt']);
  const beforeOld=await count(0);
  await c.send(0,{t:'open',sub:'old-list',query:{source:'list',account,tag:'30000:'+account+':fixture',privateLists:true},visible:true});
  await c.send(0,{t:'hint',hint:{visibleSubs:['old-list'],pageHidden:false,idle:false,saveData:false}});
  const old=await c.challenge(beforeOld);
  check('historical NIP04 is an owned read-only authorization method',old.method==='nip04_decrypt'&&old.account===account);
  fixture.release(held());
  await c.until(ms=>ms.some(m=>m.t==='state'&&m.sub==='old-list'&&m.state.privateLists?.phase==='ready'));
  fixture.configure(origin,['sign_event']);
  const otherBefore=await count(1), cancelled=await c.begin({a:'publish',as:account,what:{k:'note',draft:{text:'cancelled auth fixture'}}},1);
  const owned=await c.challenge(otherBefore,1), ownedHeld=held();
  const ownerCount=await count(0);
  await c.send(1,{t:'signer.auth.cancel',id:owned.id});await clear(owned.id,1);
  const terminal=await c.result(cancelled,1);
  check('owner cancellation settles only its own call as refused',!terminal.ok&&terminal.error?.code==='signer-refused'&&await count(0)===ownerCount);
  await c.until(()=>!fixture.open(ownedHeld));
  check('cancelled signing closes RPC and cannot publish on late approval',!fixture.release(ownedHeld)&&!fake.published.some(e=>e.content==='cancelled auth fixture'));
  const beforeRemoval=await count(0), removedPost=await c.begin({a:'publish',as:account,what:{k:'note',draft:{text:'removed auth fixture'}}});
  const removing=await c.challenge(beforeRemoval), removingHeld=held();
  const removed=await c.act({a:'account.remove',pubkey:account});await clear(removing.id);
  check('account removal clears authorization before its successful acknowledgement',removed.ok&&(await c.all(0)).findIndex(m=>m.t==='signer.auth.clear'&&m.id===removing.id)<(await c.all(0)).findIndex(m=>m.t==='result'&&m.req===removed.req));
  await c.until(()=>!fixture.open(removingHeld));fixture.release(removingHeld);
  check('revoked account cannot publish a delayed signed response',!(await c.result(removedPost)).ok&&!fake.published.some(e=>e.content==='removed auth fixture'));
  fixture.configure(origin,['connect']);
  const beforeTimeout=await count(0), timeout=await c.begin(add), expiring=await c.challenge(beforeTimeout);
  const expired=await c.control('fixture.expire');await clear(expiring.id);
  const failed=await c.result(timeout);
  check('challenge does not restart the bounded original RPC timer',expired.delays.length>0&&expired.delays.every(n=>n<=60000)&&failed.error?.code==='signer-missing');
  const beforeStop=await count(0), stopped=await c.begin(add), stopChallenge=await c.challenge(beforeStop), stopHeld=held();
  await c.control('fixture.stop');
  await c.until(()=>!fixture.open(stopHeld));
  check('stopping the retained Host aborts an outstanding authorization socket',!fixture.release(stopHeld));
  check('stopped Host cannot emit a late authorization or successful discovery',!(await c.all(0)).some(m=>m.t==='result'&&m.req===stopped&&m.ok)&&stopChallenge.id!==expiring.id);
  return {account, originalExpiry:firstExpiry};
}
