import assert from 'node:assert/strict';
import { test } from 'node:test';
import { deliver, fixture, welcome } from './engine-transport-fixture.mjs';
const ready = { t: 'ready', engine: 'rust-wasm', version: 9 };
const want = (req, url = 'https://avatars.test/one') => ({ t: 'avatar.want', req, url });
test('replays a wanted avatar before ready and removes it on the typed Blob reply', () => fixture((transport, port) => {
  const received = [];
  transport.listen((message) => received.push(message));
  const input = want('a');
  transport.post(input);
  input.url = 'https://changed.test/two';
  deliver(port, ready);
  const asks = port.sent.filter((m) => m.t === 'avatar.want');
  assert.equal(asks.length, 2);
  assert.ok(asks.every((m) => m.url === 'https://avatars.test/one'));
  const blob = new Blob(['bytes'], { type: 'image/webp' });
  const reply = { t: 'avatar', req: 'a', result: { status: 'ready', retained: true }, blob };
  deliver(port, reply);
  assert.equal(received.at(-1).blob, blob);
  deliver(port, ready);
  assert.equal(port.sent.filter((m) => m.t === 'avatar.want').length, 2);
}));
test('retains finite avatar work across dedicated leader election and fences an old epoch', () => fixture((transport, _port, state) => {
  const channel = state.channels[0], received = [];
  transport.listen((message) => received.push(message));
  transport.post(want('a'));
  assert.equal(channel.sent.filter((m) => m.msg?.t === 'avatar.want').length, 0);
  welcome(channel, 'first');
  assert.equal(channel.sent.filter((m) => m.msg?.t === 'avatar.want').length, 1);
  const target = channel.sent.find((m) => m.msg?.t === 'avatar.want').from;
  deliver(channel, { to: target, epoch: 'stale', msg: { t: 'avatar', req: 'a', result: { status: 'rejected' } } });
  assert.equal(received.some((m) => m.t === 'avatar'), false);
  deliver(channel, { to: target, epoch: 'first', msg: ready });
  assert.equal(channel.sent.filter((m) => m.msg?.t === 'avatar.want').length, 2);
  transport.post({ t: 'avatar.close', req: 'a' });
  deliver(channel, { to: target, epoch: 'first', msg: ready });
  assert.equal(channel.sent.filter((m) => m.msg?.t === 'avatar.want').length, 2);
}, true));
test('does not replay a hidden page or a cancelled avatar lease', () => fixture((transport, port) => {
  transport.post(want('a'));
  document.visibilityState = 'hidden';
  deliver(port, ready);
  assert.equal(port.sent.filter((m) => m.t === 'avatar.want').length, 1);
  transport.post({ t: 'avatar.close', req: 'a' });
  document.visibilityState = 'visible';
  deliver(port, ready);
  assert.equal(port.sent.filter((m) => m.t === 'avatar.want').length, 1);
  assert.equal(port.sent.filter((m) => m.t === 'avatar.close').length, 1);
}));
test('bounds pending replay data and returns capacity as deferred, never a plain-image fallback', () => fixture((transport, port) => {
  const received = [];
  transport.listen((message) => received.push(message));
  for (let i = 0; i < 256; i++) transport.post(want(String(i)));
  transport.post(want('overflow'));
  assert.deepEqual(received.at(-1), { t: 'avatar', req: 'overflow', result: { status: 'deferred', retryMs: 100 } });
  assert.equal(port.sent.filter((m) => m.t === 'avatar.want').length, 256);
  transport.post(want('bad-url', 'https://a.test/' + 'x'.repeat(2048)));
  assert.equal(received.at(-1).result.status, 'rejected');
  transport.post({ t: 'avatar.close', req: '0' });
  transport.post(want('overflow'));
  assert.equal(port.sent.filter((m) => m.t === 'avatar.want').length, 257);
}));
