import { publicCode } from './browser-addresses.mjs';
// Reading checks use public signed fixtures and intercepted local media only.
export async function browserReading(page,check,prefix,data) {
  const open=async label=>{ await page.locator('.brand').click(); await page.keyboard.press('Control+k'); await page.getByRole('dialog').getByRole('button',{name:label,exact:true}).first().click(); };
  await open('Global');
  const root=()=>page.locator(`.pane.focused .body.shown .note[data-id="${data.root}"]`).first();
  await root().scrollIntoViewIfNeeded();
  await page.waitForTimeout(250);
  check(`${prefix} settled activity counts omit lower-bound plus`,!(await root().locator('.actions').innerText()).includes('+'));
  const grid=root().locator('.media-grid.multiple');
  check(`${prefix} multiple images use two columns`,await grid.locator('.media').count()===2 && await grid.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length===2));
  check(`${prefix} image dimensions reserve space`,await grid.locator('.media').first().evaluate(el=>el.style.getPropertyValue('--ar').includes('1200')));
  const long=page.locator('.pane.focused .body.shown .note').filter({hasText:'読み返したいノート / Notes to return to'}).first();
  await long.scrollIntoViewIfNeeded();
  await long.getByRole('button',{name:'Show more',exact:true}).waitFor();
  const before=await long.locator('.reading-text').evaluate(el=>({height:el.clientHeight,line:parseFloat(getComputedStyle(el).lineHeight)}));
  check(`${prefix} long text folds on twelve whole lines`,Math.abs(before.height/before.line-12)<0.1);
  await long.getByRole('button',{name:'Show more',exact:true}).click();
  check(`${prefix} Show more expands in place`,await long.locator('.reading-text').evaluate(el=>el.clientHeight)>before.height);
  await long.getByRole('button',{name:'Show less',exact:true}).click();
  const media=page.locator('.pane.focused .body.shown .note').filter({hasText:'A short field recording'}).first();
  await media.scrollIntoViewIfNeeded();
  check(`${prefix} audio and video have no source before press`,await media.locator('audio,video').count()===0);
  await media.getByRole('button',{name:'Load audio',exact:true}).click();
  check(`${prefix} audio loads only on press`,await media.locator('audio[controls]').count()===1);
  await media.getByRole('button',{name:'Load video',exact:true}).click();
  check(`${prefix} video loads only on press`,await media.locator('video[controls]').count()===1);
  await open('Notifications');
  const custom=page.locator('.pane.focused .body.shown .note.compact').filter({has:page.locator('img.emoji')}).first();
  await custom.waitFor();
  check(`${prefix} notification custom reaction renders an image`,await custom.locator('header img.emoji').count()===1);
  const actor=await custom.locator('.name').getAttribute('data-profile');
  await custom.locator('.name').click();
  check(`${prefix} notification actor name opens actor profile`,new URL(page.url()).pathname.endsWith(publicCode('npub',actor)));
  await open('Global');
  const repost=page.locator('.pane.focused .body.shown .reposted button').first();
  await repost.scrollIntoViewIfNeeded();
  const reposter=await repost.getAttribute('data-profile');
  await repost.click();
  check(`${prefix} repost attribution opens reposter profile`,new URL(page.url()).pathname.endsWith(publicCode('npub',reposter)));
  await open('Global');
  await root().scrollIntoViewIfNeeded();
  const selected=await page.locator('.pane.focused .tab.active').getAttribute('data-tab');
  const tabs=await page.locator('.tab').count();
  await root().locator('.name').click({button:'middle'});
  check(`${prefix} middle actor click opens kept background tab`,await page.locator('.tab').count()===tabs+1 && await page.locator('.pane.focused .tab.active').getAttribute('data-tab')===selected);
  await page.context().setOffline(true);
  await page.waitForTimeout(50);
  check(`${prefix} offline status describes cache`,await page.locator('.topbar .status').innerText()==='offline, showing cache');
  await page.context().setOffline(false);
  await open('Settings');
  await page.locator('.pane.focused .body.shown').getByLabel('Data saver: load media on press; pause prefetch',{exact:true}).check();
  await open('Global');
  await root().scrollIntoViewIfNeeded();
  check(`${prefix} data saver covers images`,await root().getByRole('button',{name:'Load image',exact:true}).count()===2 && await root().locator('.media img').count()===0);
  await root().getByRole('button',{name:'Load image',exact:true}).first().click();
  check(`${prefix} data saver image loads after press`,await root().locator('.media img').count()===1);
  await open('Settings');
  await page.locator('.pane.focused .body.shown').getByLabel('Data saver: load media on press; pause prefetch',{exact:true}).uncheck();
}
