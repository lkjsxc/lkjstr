// Interaction regressions, run only against the intercepted fake relay.
export async function browserTabs(page, check, prefix = '') {
  const open = async (label) => {
    await page.locator('.brand').click();
    await page.keyboard.press('Control+k');
    await page.getByRole('dialog').getByRole('button', { name: label, exact: true }).first().click();
  };
  const active = () => page.locator('.pane.focused .tab.active');
  await open('Global');
  const paneId = await page.locator('.pane.focused').getAttribute('data-pane');
  const pane = page.locator(`.pane[data-pane="${paneId}"]`);
  const a = await active().getAttribute('data-tab');
  const count = await pane.locator('.tab').count();
  await open('Global');
  const b = await active().getAttribute('data-tab');
  check(`${prefix} duplicate views have distinct tabs`, a !== b && await pane.locator('.tab').count() === count + 1);
  await pane.locator(`.tab[data-tab="${a}"]`).click();
  await pane.locator(`.tab[data-tab="${b}"]`).click();
  const inactiveClose = pane.locator(`.tab[data-tab="${a}"] .x`);
  await inactiveClose.scrollIntoViewIfNeeded();
  check(`${prefix} inactive close visible`, await inactiveClose.isVisible() && Number(await inactiveClose.evaluate(el => getComputedStyle(el).opacity)) === 1);
  await pane.locator(`.tab[data-tab="${b}"]`).click({ button: 'middle' });
  check(`${prefix} middle close uses previous active`, await active().getAttribute('data-tab') === a);
  await open('Settings');
  const c = await active().getAttribute('data-tab');
  await pane.locator(`.tab[data-tab="${a}"] .x`).click();
  check(`${prefix} inactive close preserves active`, await active().getAttribute('data-tab') === c);
  await page.keyboard.press('Control+Shift+t');
  check(`${prefix} reopen restores closed tab`, await pane.locator(`.tab[data-tab="${a}"]`).count() === 1);
  await pane.locator(`.tab[data-tab="${c}"]`).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Pin', exact: true }).click();
  check(`${prefix} pin moves tab first`, await pane.locator('.tab').first().getAttribute('data-tab') === c);
  await pane.locator(`.tab[data-tab="${c}"]`).click({ button: 'right' });
  const n = await pane.locator('.tab').count();
  await page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click();
  check(`${prefix} duplicate menu adds tab`, await pane.locator('.tab').count() === n + 1);
  await page.locator('.brand').click();
  await page.keyboard.press('Alt+t');
  await page.keyboard.press('Alt+t');
  await page.keyboard.press('Alt+t');
  const x = pane.locator('.tab.active .x');
  await x.scrollIntoViewIfNeeded();
  await x.hover();
  const width = await pane.locator('.tab.active').evaluate(el => el.getBoundingClientRect().width);
  await x.click();
  const after = await pane.locator('.tab.active').evaluate(el => el.getBoundingClientRect().width);
  check(`${prefix} rapid closing preserves tab width`, Math.abs(width - after) < 1);
  await page.waitForTimeout(50);
  check(`${prefix} close returns focus to active tab`, await pane.locator('.tab.active').evaluate(el => document.activeElement === el));
  const source = pane.locator('.tab.active');
  const sourceId = await source.getAttribute('data-tab');
  const box = await source.boundingBox();
  await page.mouse.move(box.x + 10, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + 80, box.y + 70, { steps: 5 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  check(`${prefix} Escape cancels drag without losing tab`, await pane.locator(`.tab[data-tab="${sourceId}"]`).count() === 1 && await page.locator('.drag-ghost').count() === 0);
  await pane.getByRole('button', { name: 'All tabs', exact: true }).click();
  await pane.getByRole('searchbox', { name: 'Filter tabs' }).fill('Settings');
  check(`${prefix} all tabs filters titles`, await pane.locator('.all-tabs').getByRole('menuitem').count() >= 1);
  await pane.locator('.all-tabs').getByRole('menuitem').first().click();
}
