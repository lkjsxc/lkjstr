//! Fixed-seed generator for repeatable native fixtures and future exploration.
#[cfg(test)]
pub(super) struct Random(u64);

#[cfg(test)]
impl Random {
    pub fn new(seed: u64) -> Self {
        Self(seed.max(1))
    }

    pub fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(2_685_821_657_736_338_717)
    }
}
